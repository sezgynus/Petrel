#!/usr/bin/env bash
set -euo pipefail

INSTALL_USER="${SUDO_USER:-$USER}"
INSTALL_HOME="$(getent passwd "$INSTALL_USER" | cut -d: -f6)"
REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CONFIG_DIR="$INSTALL_HOME/.config/Petrel"
ENV_FILE="$CONFIG_DIR/Petrel.env"

read_value() {
    local key="$1"
    local default="$2"
    local value=""
    if [[ -f "$ENV_FILE" ]]; then
        value="$(sed -n "s/^${key}=//p" "$ENV_FILE" | tail -n 1)"
        value="${value%\"}"
        value="${value#\"}"
    fi
    printf '%s' "${value:-$default}"
}

prompt_value() {
    local label="$1"
    local current="$2"
    local result=""
    read -r -p "$label [$current]: " result || true
    printf '%s' "${result:-$current}"
}

mkdir -p "$CONFIG_DIR"

moonraker_url="$(prompt_value "Moonraker URL" "$(read_value MOONRAKER_URL http://127.0.0.1:7125)")"
serial_port="$(prompt_value "Serial port" "$(read_value PETREL_SERIAL_PORT /dev/ttyS0)")"
encoder_a="$(read_value PETREL_ENCODER_PINS "21 19")"
encoder_a="${encoder_a%% *}"
encoder_b_raw="$(read_value PETREL_ENCODER_PINS "21 19")"
encoder_b="${encoder_b_raw#* }"
encoder_a="$(prompt_value "Encoder A GPIO (BCM)" "$encoder_a")"
encoder_b="$(prompt_value "Encoder B GPIO (BCM)" "$encoder_b")"
button_pin="$(prompt_value "Encoder button GPIO (BCM)" "$(read_value PETREL_BUTTON_PIN 20)")"
power_device="$(prompt_value "Moonraker power device" "$(read_value PETREL_POWER_DEVICE Printer)")"
power_on_hold_ms="$(prompt_value "Power-on button hold time (ms, 0 = immediate)" "$(read_value PETREL_POWER_ON_HOLD_MS 2000)")"
if ! [[ "$power_on_hold_ms" =~ ^[0-9]+$ ]]; then
    echo "Power-on button hold time must be zero or a positive integer." >&2
    exit 1
fi
request_timeout="$(read_value PETREL_REQUEST_TIMEOUT 5)"
api_key="$(read_value MOONRAKER_API_KEY "")"
settings_file="$(read_value PETREL_SETTINGS_FILE "$CONFIG_DIR/presets.json")"
emulator="$(read_value PETREL_EMULATOR 0)"

echo "Optional Klipper extra: X/Y/Z travel and event-based sensor counters for maintenance reminders."
echo "Installs a symlink and a managed printer.cfg include; adds bounded background work."
echo "Restart Klipper while idle to apply changes. Run configure.sh again to disable."
axis_travel="$(prompt_value "Enable axis travel and sensor event counters? (1=yes, 0=no)" "$(read_value PETREL_AXIS_TRAVEL 1)")"
if [[ "$axis_travel" != 0 && "$axis_travel" != 1 ]]; then
    echo "Axis travel must be 1 or 0." >&2
    exit 1
fi
klipper_dir="$(read_value PETREL_KLIPPER_DIR "$INSTALL_HOME/klipper")"
printer_config="$(read_value PETREL_PRINTER_CONFIG "$INSTALL_HOME/printer_data/config/printer.cfg")"
if [[ "$axis_travel" == 1 ]]; then
    klipper_dir="$(prompt_value "Klipper repository path" "$klipper_dir")"
    printer_config="$(prompt_value "Klipper main configuration path" "$printer_config")"
fi
python3 "$REPO_DIR/tools/axis_travel_install.py" --enabled "$axis_travel" \
    --repo "$REPO_DIR" --klipper "$klipper_dir" --printer-config "$printer_config" \
    --manifest "$CONFIG_DIR/axis-travel-install.json"

emulator="$(prompt_value "Enable emulator / screenshot capture? (1=yes, 0=no)" "$emulator")"
echo "Remote display provides browser viewing and encoder control; it also starts the emulator."
echo "Remote host/port settings are preserved (default: 0.0.0.0:8088)."
remote="$(prompt_value "Enable remote display? (1=yes, 0=no)" "$(read_value PETREL_REMOTE 0)")"
aux_current="$(read_value PETREL_AUX_UART 0)"
echo "Optional DWIN auxiliary UART: standard Linux serial port, 8N1, baud >=15300."
echo "Enabling installs a DKMS driver and shared transport service. Disabling removes them."
aux_uart="$(prompt_value "Enable DWIN auxiliary UART? (1=yes, 0=no)" "$aux_current")"
if [[ "$aux_uart" != 0 && "$aux_uart" != 1 ]]; then
    echo "DWIN auxiliary UART must be 1 or 0." >&2
    exit 1
fi
for flag in "$emulator" "$remote"; do
    case "${flag,,}" in
        0|1|true|false|yes|no|on|off) ;;
        *) echo "Emulator and remote display must use 1/0 or true/false, yes/no, on/off." >&2; exit 1 ;;
    esac
done

# Complete the optional installation before persisting its requested state.
if [[ "$aux_uart" == 1 || "$aux_current" == 1 || -f /var/lib/Petrel/dwin-uart.json ]]; then
    sudo python3 "$REPO_DIR/tools/dwin_uart_install.py" --enabled "$aux_uart" \
        --repo "$REPO_DIR" --home "$INSTALL_HOME" --user "$INSTALL_USER" --port "$serial_port"
fi

# Keep custom EnvironmentFile assignments verbatim; never evaluate their contents.
additional_settings=""
if [[ -f "$ENV_FILE" ]]; then
    additional_settings="$(sed -E \
        '/^(MOONRAKER_URL|MOONRAKER_API_KEY|PETREL_REQUEST_TIMEOUT|PETREL_SERIAL_PORT|PETREL_ENCODER_PINS|PETREL_BUTTON_PIN|PETREL_SETTINGS_FILE|PETREL_POWER_DEVICE|PETREL_POWER_ON_HOLD_MS|PETREL_EMULATOR|PETREL_REMOTE|PETREL_AUX_UART|PETREL_AXIS_TRAVEL|PETREL_KLIPPER_DIR|PETREL_PRINTER_CONFIG)=/d; /^# Petrel runtime configuration\.$/d; /^# Generated by configure\.sh\./d' \
        "$ENV_FILE")"
fi

# Restrict permissions before writing API keys, then replace the file atomically.
umask 077
new_env="$(mktemp "$CONFIG_DIR/.Petrel.env.XXXXXX")"
trap 'rm -f -- "$new_env"' EXIT
cat > "$new_env" <<EOF
# Petrel runtime configuration.
# Generated by configure.sh. Values use systemd EnvironmentFile syntax.
MOONRAKER_URL=$moonraker_url
MOONRAKER_API_KEY=$api_key
PETREL_REQUEST_TIMEOUT=$request_timeout
PETREL_SERIAL_PORT=$serial_port
PETREL_ENCODER_PINS="$encoder_a $encoder_b"
PETREL_BUTTON_PIN=$button_pin
PETREL_SETTINGS_FILE=$settings_file
PETREL_POWER_DEVICE=$power_device
PETREL_POWER_ON_HOLD_MS=$power_on_hold_ms
PETREL_EMULATOR=$emulator
PETREL_REMOTE=$remote
PETREL_AUX_UART=$aux_uart
PETREL_AXIS_TRAVEL=$axis_travel
PETREL_KLIPPER_DIR="$klipper_dir"
PETREL_PRINTER_CONFIG="$printer_config"
EOF
if [[ -n "$additional_settings" ]]; then
    printf '%s\n' "$additional_settings" >> "$new_env"
fi

chown "$INSTALL_USER:$INSTALL_USER" "$new_env"
chmod 600 "$new_env"
mv -- "$new_env" "$ENV_FILE"
trap - EXIT

echo
echo "Configuration saved to $ENV_FILE"

if systemctl list-unit-files Petrel.service >/dev/null 2>&1; then
    answer=""
    read -r -p "Restart Petrel now? [Y/n]: " answer
    case "${answer:-Y}" in
        [Yy]*)
            sudo systemctl restart Petrel.service
            echo "Petrel.service restarted."
            ;;
    esac
fi
